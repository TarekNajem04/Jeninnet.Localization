-- ============================================================================
-- LocalizationMessages — fresh-database schema (PostgreSQL)
-- Project : Jeninnet.Localization
-- Purpose : Create the canonical message table on a database that does not
--           have it yet.
--
-- This script is idempotent: when public."LocalizationMessages" already exists
-- it does nothing and never drops or alters the existing table. If the database
-- still has the pre-canonical ValidationMessages table, do not run this script:
-- see ../README.md for the SQL Server rename migration and vendor limitations.
--
-- Canonical schema (FINAL_ARCHITECTURE.md §14):
--     Table   : LocalizationMessages
--     Columns : Id, MessageKey, Culture, Template
--     Keys    : PRIMARY KEY (Id), UNIQUE (MessageKey, Culture)
--
-- The script targets the default public schema. Replace public with your
-- application schema when the table lives elsewhere. PostgreSQL string
-- equality is case-sensitive by default; citext would change that behavior.
-- ============================================================================

CREATE TABLE IF NOT EXISTS public."LocalizationMessages"
(
    "Id"         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "MessageKey" VARCHAR(255) NOT NULL,
    "Culture"    VARCHAR(64)  NOT NULL,
    "Template"   TEXT         NOT NULL,
    CONSTRAINT "PK_LocalizationMessages"
        PRIMARY KEY ("Id"),
    CONSTRAINT "UQ_LocalizationMessages_MessageKey_Culture"
        UNIQUE ("MessageKey", "Culture")
);
