namespace Jeninnet.Localization.Generators.Keys;

/// <summary>
/// One sanitized key ready for emission, in ordinal sort order.
/// </summary>
/// <param name="key">The catalog key.</param>
/// <param name="identifier">The generated constant name.</param>
internal sealed class EmittedKey(string key, string identifier) {

    /// <summary>
    /// Gets the catalog key.
    /// </summary>
    public string Key { get; } = key;

    /// <summary>
    /// Gets the generated constant name.
    /// </summary>
    public string Identifier { get; } = identifier;
}

/// <summary>
/// Renders the generated compilation unit as text: one
/// <c>public static partial class LocalizationKeys</c> with a <c>const string</c> per
/// catalog key plus a keys-only <c>All</c> table. Pure function of the namespace and
/// the ordinal-sorted keys: no timestamps, no machine data, no dictionary-ordering
/// dependence — byte-identical across rebuilds for fixed inputs. Classic C# syntax
/// only, so any consumer language version compiles the output.
/// </summary>
internal static class KeysSourceBuilder {
    /// <summary>
    /// Renders the generated source.
    /// </summary>
    /// <param name="namespaceName">The namespace of the generated class.</param>
    /// <param name="keys">The keys in ordinal sort order with their identifiers.</param>
    /// <returns>The compilation unit text.</returns>
    /// <exception cref="ArgumentNullException">Thrown when <paramref name="namespaceName"/> or <paramref name="keys"/> is <see langword="null"/>.</exception>
    public static string Build(string namespaceName, IReadOnlyList<EmittedKey> keys) {
        if(namespaceName is null) {
            throw new ArgumentNullException(nameof(namespaceName));
        }

        if(keys is null) {
            throw new ArgumentNullException(nameof(keys));
        }

        var builder = new StringBuilder();
        builder.Append("// <auto-generated/>\n")
            .Append("// Localization keys generated from canonical JSON catalogs.\n")
            .Append("// Keys only: templates stay in providers and are never baked into code.\n")
            .Append("#nullable enable\n")
            .Append("namespace ")
            .Append(namespaceName)
            .Append(";\n")
            .Append('\n')
            .Append("/// <summary>\n")
            .Append("/// Strongly-typed localization keys: typos become build errors and renames\n")
            .Append("/// propagate through compilation instead of failing at runtime.\n")
            .Append("/// </summary>\n")
            .Append("public static partial class LocalizationKeys {\n");
        for(var index = 0; index < keys.Count; index++) {
            var key = keys[index];
            builder.Append("    /// <summary>Localization key \"")
                .Append(LocalizationKeyNaming.EscapeLiteral(key.Key))
                .Append("\".</summary>\n")
                .Append("    public const string ")
                .Append(key.Identifier)
                .Append(" = \"")
                .Append(LocalizationKeyNaming.EscapeLiteral(key.Key))
                .Append("\";\n");
        }

        builder.Append('\n')
            .Append("    /// <summary>Every generated key, in ordinal sort order.</summary>\n")
            .Append("    public static readonly string[] All = new string[] {");
        for(var index = 0; index < keys.Count; index++) {
            if(index > 0) {
                builder.Append(", ");
            }

            builder.Append('"')
                .Append(LocalizationKeyNaming.EscapeLiteral(keys[index].Key))
                .Append('"');
        }

        builder.Append("};\n")
            .Append("}\n");
        return builder.ToString();
    }
}
